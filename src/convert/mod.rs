//! Rewriting comics as new CBZ files: CBR → CBZ conversion and AVIF compression.
//!
//! Both work the same way: extract to a temporary directory, optionally
//! transform the pages, pack a new CBZ beside the original, then move the
//! original to the system trash.

mod avif;

use std::fs;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail};

pub use avif::{CompressOptions, check_avifenc};

use crate::archive;

/// Disposes of an original once its replacement is ready.
type Dispose = fn(&Path) -> Result<()>;

fn move_to_trash(path: &Path) -> Result<()> {
    trash::delete(path).context("failed to move the original to the trash")
}

/// Repacks `path` (any supported archive) as `<name>.cbz`. Returns the new path.
pub fn convert_to_cbz(path: &Path) -> Result<PathBuf> {
    convert_to_cbz_with(path, move_to_trash)
}

/// Re-encodes the pages of `path` as AVIF and saves it as `<name>.cbz`.
/// Returns the new path, which is unchanged if there was nothing to compress.
pub fn compress_avif(path: &Path, options: CompressOptions) -> Result<PathBuf> {
    compress_avif_with(path, options, move_to_trash)
}

fn convert_to_cbz_with(path: &Path, dispose: Dispose) -> Result<PathBuf> {
    let work = tempfile::tempdir()?;
    archive::extract_all(path, work.path())?;
    replace_with_cbz(path, work.path(), dispose)
}

fn compress_avif_with(path: &Path, options: CompressOptions, dispose: Dispose) -> Result<PathBuf> {
    let work = tempfile::tempdir()?;
    archive::extract_all(path, work.path())?;

    if avif::encode_directory(work.path(), options)? == 0 {
        return Ok(path.to_path_buf());
    }
    replace_with_cbz(path, work.path(), dispose)
}

/// Packs `dir` into `<original stem>.cbz` beside `original`, then disposes of
/// `original`. Returns the new path.
fn replace_with_cbz(original: &Path, dir: &Path, dispose: Dispose) -> Result<PathBuf> {
    let target = original.with_extension("cbz");
    if target != original && target.exists() {
        bail!("{} already exists", target.display());
    }

    let parent = original.parent().context("file has no parent directory")?;
    let mut temp = tempfile::Builder::new()
        .prefix(".comic-editor-")
        .suffix(".cbz")
        .tempfile_in(parent)?;
    archive::pack_directory(dir, temp.as_file_mut())?;
    temp.as_file().set_permissions(fs::metadata(original)?.permissions())?;

    dispose(original)?;
    temp.persist(&target).with_context(|| {
        format!("failed to save {} (the original was already moved to the trash)", target.display())
    })?;
    Ok(target)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::archive::{Format, read_summary};

    fn delete(path: &Path) -> Result<()> {
        Ok(fs::remove_file(path)?)
    }

    /// Writes a zip with real JPEG pages (generated by `magick`) and a ComicInfo.xml.
    fn make_comic(path: &Path) {
        let pages = tempfile::tempdir().unwrap();
        for i in 1..=3 {
            let status = std::process::Command::new("magick")
                .args(["-size", "600x900", "plasma:", "-quality", "95"])
                .arg(pages.path().join(format!("{i:03}.jpg")))
                .status()
                .expect("magick is needed for this test");
            assert!(status.success());
        }
        fs::write(pages.path().join("ComicInfo.xml"), "<ComicInfo><Series>Test</Series></ComicInfo>").unwrap();
        archive::pack_directory(pages.path(), &mut fs::File::create(path).unwrap()).unwrap();
    }

    #[test]
    fn converts_mislabelled_cbr_to_cbz() {
        let dir = tempfile::tempdir().unwrap();
        let cbr = dir.path().join("Issue 1.cbr");
        make_comic(&cbr);

        let cbz = convert_to_cbz_with(&cbr, delete).unwrap();
        assert_eq!(cbz, dir.path().join("Issue 1.cbz"));
        assert!(!cbr.exists());

        let summary = read_summary(&cbz).unwrap();
        assert_eq!(summary.format, Format::Cbz);
        assert_eq!(summary.page_count, 3);
        assert_eq!(summary.comic_info.unwrap().get("Series"), Some("Test"));
    }

    #[test]
    fn refuses_to_overwrite_existing_cbz() {
        let dir = tempfile::tempdir().unwrap();
        let cbr = dir.path().join("a.cbr");
        make_comic(&cbr);
        fs::write(dir.path().join("a.cbz"), "existing").unwrap();
        assert!(convert_to_cbz_with(&cbr, delete).is_err());
        assert!(cbr.exists(), "original must survive a failed conversion");
    }

    #[test]
    #[ignore = "needs avifenc; run with --ignored"]
    fn compresses_pages_to_avif() {
        let dir = tempfile::tempdir().unwrap();
        let cbz = dir.path().join("a.cbz");
        make_comic(&cbz);
        let before = fs::metadata(&cbz).unwrap().len();

        let out = compress_avif_with(&cbz, CompressOptions::default(), delete).unwrap();
        assert_eq!(out, cbz);
        let after = fs::metadata(&cbz).unwrap().len();
        assert!(after < before, "{after} should be smaller than {before}");

        let mut zip = zip::ZipArchive::new(fs::File::open(&cbz).unwrap()).unwrap();
        let names: Vec<_> = zip.file_names().map(str::to_owned).collect();
        assert!(names.iter().all(|n| !n.ends_with(".jpg")), "{names:?}");
        assert!(zip.by_name("ComicInfo.xml").is_ok());
        assert_eq!(fs::read_dir(dir.path()).unwrap().count(), 1, "no temp files left behind");
    }
}
